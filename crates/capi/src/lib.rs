//! `liborion`'s core: the C surface over Orion's stable interface (docs/design/stable-interface.md,
//! step 7; docs/capi.md).
//!
//! - [`link::LinkClient`]: a blocking client session on a node's `unix:` link, status queries and
//!   watches, on one socket the caller may poll.
//! - [`latest::LatestClient`]: a blocking client for the fd latest-value channel.
//! - The `orion_*` functions: those two behind opaque handles, with the shared ABI vocabulary
//!   (status codes, handles, the version handshake, message sinks) of the `abi` crate.
//!
//! The library itself is `crates/liborion` (static and shared); this crate is its Rust core, used
//! directly by Rust callers and tests. The header is `include/orion/orion.h`, generated by
//! cbindgen (`scripts/capi.sh header`) and checked in CI.

#![cfg(unix)]

pub mod latest;
pub mod link;

mod surface;

pub use surface::*;
